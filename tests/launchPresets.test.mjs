import assert from "node:assert/strict";
import * as m from "../src/launchPresets.ts";
const P = id => m.LAUNCH_PRESETS.find(p => p.id === id);
const on=(id,o)=>m.setPreset(P(id),o,true), off=(id,o)=>m.setPreset(P(id),o,false);
assert.equal(on("wined3d",""),"PROTON_USE_WINED3D=1 %command%");
assert.equal(off("wined3d","PROTON_USE_WINED3D=1 %command%"),"");
assert.equal(on("unreal-dx11",""),"%command% -dx11");
assert.equal(on("no-fsync","-windowed"),"PROTON_NO_FSYNC=1 %command% -windowed");
const fp="run --branch=stable --arch=x86_64 com.google.Chrome";
assert.equal(off("mangohud",on("mangohud",fp)),"%command% "+fp);
assert.equal(on("mangohud","gamescope -- %command% -x"),"MANGOHUD=1 gamescope -- %command% -x");
assert.equal(on("no-fsync","FOO=1 gamemoderun %command%"),"FOO=1 PROTON_NO_FSYNC=1 gamemoderun %command%");
assert.equal(on("dll-winmm","gamemoderun %command%"),'WINEDLLOVERRIDES="winmm=n,b" gamemoderun %command%');
assert.equal(on("wined3d","PROTON_USE_WINED3D=0 %command%"),"PROTON_USE_WINED3D=1 %command%");
let d=on("dll-dinput8",""); assert.equal(d,'WINEDLLOVERRIDES="dinput8=n,b" %command%');
d=on("dll-winhttp",d); assert.equal(d,'WINEDLLOVERRIDES="dinput8,winhttp=n,b" %command%');
assert.ok(m.isPresetOn(P("dll-winhttp"),d)); assert.ok(!m.isPresetOn(P("dll-winmm"),d));
d=off("dll-dinput8",d); assert.equal(d,'WINEDLLOVERRIDES="winhttp=n,b" %command%');
assert.equal(off("dll-winhttp",d),"");
assert.equal(on("dll-winmm",'WINEDLLOVERRIDES="openal32=b" %command%'),'WINEDLLOVERRIDES="openal32=b;winmm=n,b" %command%');
assert.ok(m.isPresetOn(P("cpu-limit"),"PROTON_CPU_TOPOLOGY=4:0,1,2,3 %command%"));
assert.ok(!m.isPresetOn(P("mangohud"),"%command% MANGOHUD=1"));
assert.equal(new Set(m.LAUNCH_PRESETS.map(p=>p.id)).size,m.LAUNCH_PRESETS.length);
console.log("presets ok,",m.LAUNCH_PRESETS.length);
